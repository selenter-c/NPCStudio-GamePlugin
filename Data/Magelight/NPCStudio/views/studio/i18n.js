function T(Text) {
  if (typeof Text !== 'string') return Text
  if (Language === 'ru') return RussianMessages[Text] || Text
  let Match = Text.match(/^Снаряжение восстановлено\. Проверено вещей: (\d+); динамических пропущено: (\d+)$/)
  if (Match) return `Equipment restored. Checked: ${Match[1]}; dynamic items skipped: ${Match[2]}`
  Match = Text.match(/^Недостача: (\d+); не надето: (\d+)\. Проверьте снаряжение$/)
  if (Match) return `Missing: ${Match[1]}; not equipped: ${Match[2]}. Check equipment`
  if (English[Text] !== undefined) return English[Text]
  const Trimmed = Text.replace(/\s+/g, ' ').trim()
  if (English[Trimmed] !== undefined) return English[Trimmed]
  return Text
}
function ApplyLocale(Value) {
  if (ApplyLocale.value === Value) return
  Language = Value === 'ru' ? 'ru' : 'en'
  ApplyLocale.value = Value
  document.documentElement.lang = Language
  for (const [Node, Text] of StaticText) if (Node.isConnected) Node.textContent = T(Text)
  for (const [Element, Attribute, Text] of StaticAttributes) Element.setAttribute(Attribute, T(Text))
  PickTip()
}
